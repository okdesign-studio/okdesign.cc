const s = (id, label, p) => ({ id, label, p });
const flatSize = (id, label, w, h, extra) => s(id, label, { w, h, ...extra });
const A_SIZES = (list, extra) =>
  list.map((k) => flatSize(k, `${k.toUpperCase()} ${A[k][0]} × ${A[k][1]} mm`, A[k][0], A[k][1], extra));

// A leaflet size: flat width and height, plus how it reads once folded.
const leaf = (id, label, w, h, extra) => s(id, label, { w, h, ...extra });

